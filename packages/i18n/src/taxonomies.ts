export type TaxonomyGroup = 'bodyParts' | 'targets' | 'equipments' | 'secondaryMuscles';

export function getLocalizedTaxonomy(
  groupOrCatalog: TaxonomyGroup | Record<string, { es: string; en: string }>,
  key: string,
  locale: 'es' | 'en' = 'es'
): string {
  if (!key) return '';
  let catalog: Record<string, { es: string; en: string }>;
  if (typeof groupOrCatalog === 'string') {
    switch (groupOrCatalog) {
      case 'bodyParts':
        catalog = BODY_PARTS_I18N;
        break;
      case 'targets':
        catalog = TARGET_MUSCLES_I18N;
        break;
      case 'equipments':
        catalog = EQUIPMENT_I18N;
        break;
      case 'secondaryMuscles':
        catalog = SECONDARY_MUSCLES_I18N;
        break;
      default:
        return key.charAt(0).toUpperCase() + key.slice(1);
    }
  } else {
    catalog = groupOrCatalog;
  }
  const lower = key.toLowerCase().trim();
  const entry = catalog[lower];
  if (entry && entry[locale]) return entry[locale];
  // Fallback capitalizado
  return key.charAt(0).toUpperCase() + key.slice(1);
}
